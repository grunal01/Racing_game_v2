"""Pack the Kenney models in assets/ into js/assets.js, so the game runs from a single file (even opened straight from disk).

Run from the repo root:  python3 tools/pack_assets.py
"""
import base64, json, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
out = {"cars": {}, "nature": {}, "tex": {}}
for kind in ("cars", "nature"):
    for f in sorted((root / "assets" / kind).glob("*.glb")):
        out[kind][f.stem] = base64.b64encode(f.read_bytes()).decode()
out["tex"]["Textures/colormap.png"] = "data:image/png;base64," + base64.b64encode((root / "assets/cars/colormap.png").read_bytes()).decode()
js = "// Generated by tools/pack_assets.py from assets/ (Kenney Car Kit and Nature Kit, CC0). Don't edit by hand.\nwindow.ASSETS = " + json.dumps(out, separators=(",", ":")) + ";\n"
(root / "js" / "assets.js").write_text(js)
print("wrote js/assets.js", len(js) // 1024, "KB:", len(out["cars"]), "cars,", len(out["nature"]), "nature models")
